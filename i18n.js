/** Save the app language and reload so every screen is rebuilt in it. */
export function saveLang(l) { try { localStorage.setItem('pm.lang', norm(l)); } catch {} location.reload(); }
function look(d, s) {
  if (d[s] != null) return d[s];
  const tt = s.trim().replace(/\s+/g, ' ');
  if (tt && d[tt] != null) return s.replace(s.trim(), d[tt]);
  return null;
}
/** Translate a key into a given language; {0},{1}… are filled from args. HTML keys are translated piece by piece. */
export function tl(lang, key, args) {
  let s = String(key);
  if (lang !== 'vi') {
    const d = D[lang], hit = look(d, s);
    if (hit != null) s = hit;
    else if (/[<{]/.test(s)) s = s.replace(/(^|>|\})([^<>{}]+)(?=<|\{|$)/g, (m, pre, txt) => { const r = look(d, txt); return pre + (r != null ? r : txt); })
      .replace(/\b(aria-label|title|placeholder)="([^"{}]+)"/g, (m, a, v) => { const r = look(d, v); return r != null ? `${a}="${r}"` : m; });
  }
  if (lang !== 'vi' && /[ăâđêôơưạảấầẩẫậắằẳẵặẹẻẽếềểễệịỉĩọỏốồổỗộớờởỡợụủũứừửữựỳỷỹỵ]/i.test(s)) (globalThis.__i18nMiss ||= new Set()).add(String(key));
  if (args) s = s.replace(/\{(\d+)\}/g, (m, i) => (args[i] ?? ''));
  return s.replace(/\{\{/g, '{').replace(/\}\}/g, '}');
}
export const t = (key, args) => tl(LANG, key, args);
/** Translate the static HTML (text nodes + placeholder / aria-label / title). */
export function translateDOM(root = document.body) {
  if (LANG === 'vi') return;
  const d = D[LANG];
  const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = []; while (w.nextNode()) nodes.push(w.currentNode);
  for (const n of nodes) { if (!n.nodeValue.trim() || n.parentNode?.closest?.('script,style,svg')) continue; const r = look(d, n.nodeValue); if (r != null) n.nodeValue = r; }
  root.querySelectorAll('[placeholder],[aria-label],[title]').forEach(el => {
    for (const a of ['placeholder', 'aria-label', 'title']) { const v = el.getAttribute(a); if (v) { const r = look(d, v); if (r != null) el.setAttribute(a, r); } }
  });
}
